def minimo(metodo,caminho,parametros=None):
    """Nível mínimo da rota (nome do papel). Sem regra: plataforma."""
    if caminho.startswith('/admin/v1'): caminho=caminho[len('/admin/v1'):]
    if '{entidade}' in caminho:
        return ENTIDADES.get((parametros or {}).get('entidade'),{}).get(metodo,'plataforma')
    return PERMISSOES.get((metodo,caminho),'plataforma')


def atende(papel,minimo_):
    return NIVEIS.get(papel,0)>=NIVEIS[minimo_]
